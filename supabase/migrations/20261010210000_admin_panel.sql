create extension if not exists pgcrypto;

create or replace function public.is_dmaestros_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) = 'dmaestros.cl@gmail.com';
$$;

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  sku text not null unique,
  name text not null,
  description text not null default '',
  category_id uuid references public.categories(id) on delete set null,
  image_url text not null default '',
  price numeric(12,2),
  stock integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_email text not null,
  status text not null default 'pendiente' check (status in ('pendiente','pagado','preparando','enviado','entregado','cancelado')),
  shipping_status text not null default 'por_preparar' check (shipping_status in ('por_preparar','preparado','despachado','entregado')),
  total numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.shipping_methods (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  regions text not null default 'Todo Chile',
  price numeric(12,2) not null default 0,
  estimated_days text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.hero_slides (
  id uuid primary key default gen_random_uuid(),
  mobile_image_url text not null,
  desktop_image_url text not null,
  alt text not null default '',
  title text not null,
  description text not null default '',
  cta text not null default 'Conoce nuestras piezas',
  href text not null default '/tienda',
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.shipping_methods enable row level security;
alter table public.hero_slides enable row level security;

create policy "Public reads active categories" on public.categories for select using (active or public.is_dmaestros_admin());
create policy "Admin manages categories" on public.categories for all using (public.is_dmaestros_admin()) with check (public.is_dmaestros_admin());
create policy "Public reads active products" on public.products for select using (active or public.is_dmaestros_admin());
create policy "Admin manages products" on public.products for all using (public.is_dmaestros_admin()) with check (public.is_dmaestros_admin());
create policy "Admin manages orders" on public.orders for all using (public.is_dmaestros_admin()) with check (public.is_dmaestros_admin());
create policy "Public reads active shipping" on public.shipping_methods for select using (active or public.is_dmaestros_admin());
create policy "Admin manages shipping" on public.shipping_methods for all using (public.is_dmaestros_admin()) with check (public.is_dmaestros_admin());
create policy "Public reads active hero slides" on public.hero_slides for select using (active or public.is_dmaestros_admin());
create policy "Admin manages hero slides" on public.hero_slides for all using (public.is_dmaestros_admin()) with check (public.is_dmaestros_admin());

